
select 
    --ORDER FIELDS 
    O.ORDERID, 
    O.ORDERDATE, 
    O.SHIPDATE, 
    O.SHIPMODE, 
    O.CUSTOMERID, 
    O.PRODUCTID, 
    O.ORDERCOSTPRICE, 
    O.ORDERSELLINGPRICE,
    --CUSTOMER FIELDS
    C.CUSTOMERID AS CUSTOMER_ID, 
    C.CUSTOMERNAME, 
    C.SEGMENT, 
    C.COUNTRY, 
    C.STATE,
    --PRODUCT FIELDS
    P.CATEGORY, 
    P.PRODUCTID AS PRODUCT_ID, 
    P.PRODUCTNAME, 
    P.SUBCATEGORY
from {{ ref('ORDERS') }} O
LEFT JOIN 
{{ ref('CUSTOMER') }} C
ON O.CUSTOMERID = C.CUSTOMERID
LEFT  JOIN
{{ ref('PRODUCT') }} P
ON O.PRODUCTID = P.PRODUCTID